#!/usr/bin/env python3
"""Generate RV64M self-checking ELFs' sources from arbitrary-precision arithmetic."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MASK = (1 << 64) - 1
OPS = ["mul", "mulh", "mulhsu", "mulhu", "div", "divu", "rem", "remu",
       "mulw", "divw", "divuw", "remw", "remuw"]


def signed(x, bits):
    return (x & ((1 << bits) - 1)) - ((x >> (bits - 1) & 1) << bits)


def expected(op, a, b):
    bits = 32 if op.endswith("w") else 64
    lowmask = (1 << bits) - 1
    if op == "mulh":
        value = (signed(a, 64) * signed(b, 64)) >> 64
    elif op == "mulhsu":
        value = (signed(a, 64) * b) >> 64
    elif op == "mulhu":
        value = (a * b) >> 64
    elif op.startswith("mul"):
        value = a * b
    else:
        x, y = (a & lowmask, b & lowmask) if "u" in op else (signed(a, bits), signed(b, bits))
        quotient = -1 if y == 0 else (abs(x) // abs(y)) * (-1 if (x < 0) != (y < 0) else 1)
        value = quotient if op.startswith("div") else (x if y == 0 else x - quotient * y)
    return (signed(value, 32) if bits == 32 else value) & MASK


def main():
    output = ROOT / "tests/rv64-m"
    output.mkdir(exist_ok=True)
    (output / "link.ld").write_text((ROOT / "tests/rv64-memory/link.ld").read_text())
    edges = [0, 1, 2, 3, MASK, MASK - 1, 1 << 63, (1 << 63) - 1,
             0x80000000, 0xffffffff, 0x1234567887654321]
    for index, op in enumerate(OPS):
        cases = [(a, b, expected(op, a, b)) for a in edges for b in edges]
        text = f'''# Generated by riscv/tools/generate_rv64_m_tests.py.
.include "test_macros.inc"
.section .text.init, "ax", @progbits
.globl _start
_start:
    la s0, cases
    li s1, {len(cases)}
loop:
    ld a0, 0(s0)
    ld a1, 8(s0)
    ld a2, 16(s0)
    {op} a3, a0, a1
    bne a3, a2, fail
    # Both a dependent consumer and an aliased destination must work.
    addi a4, a3, 1
    addi a4, a4, -1
    bne a4, a2, fail
    {op} a0, a0, a1
    bne a0, a2, fail
    addi s0, s0, 24
    addi s1, s1, -1
    bnez s1, loop
    {op} zero, a0, a1
    bnez zero, fail
    PASS
fail:
    FAIL {index + 20}
.section .rodata, "a", @progbits
.balign 8
cases:
'''
        text += "".join("    .dword " + ", ".join(f"0x{x:016x}" for x in row) + "\n" for row in cases)
        (output / f"{op}.S").write_text(text)


if __name__ == "__main__":
    main()
