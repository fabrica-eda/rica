#!/usr/bin/env python3
"""Generate/check the U-platform RTL constants and PLL from one profile."""
import argparse
import json
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
# Templates come unmodified from ecppll through tools/pll_template_from_ecppll.py
# (12 MHz phase detector, internal CLKOP feedback, zero CLKOS/CLKOS2 phase).
PLL_TEMPLATES = {
    624_000_000: 'pll-12-to-124p8.json',
    588_000_000: 'pll-12-to-84.json',
    648_000_000: 'pll-12-to-108.json',
    672_000_000: 'pll-12-to-112.json',
}


def load_profile(path=None):
    p = json.loads((path or PROJECT / 'platform-user.json').read_text())
    if (p['reference_hz'] != 12_000_000 or p['vco_hz'] not in PLL_TEMPLATES
            or any(type(p[name]) is not int or p[name] <= 0 for name in ('cpu_hz', 'memory_hz'))
            or p['cpu_hz'] % p['memory_hz'] != 0
            or p['cpu_hz'] // p['memory_hz'] not in (1, 2)
            or p['pmp_data_stages'] not in (2, 3)
            or type(p.get('early_alu', False)) is not bool
            or type(p.get('direct_load_return', False)) is not bool
            or (p.get('direct_load_return', False) and p['cpu_hz'] != p['memory_hz'])
            or p['setup_hold_guard_ps'] != 194):
        raise ValueError('invalid U-platform clock/stage configuration')
    for hz in (p['cpu_hz'], p['memory_hz']):
        if p['vco_hz'] % hz != 0 or not 1 <= p['vco_hz'] // hz <= 128:
            raise ValueError('frequency cannot be generated by the platform PLL')
    return p


def check_checkpoint_clocks(cp, profile_path, integrated_jtck=True):
    """Require the physical PLL parameters as well as the derived STA periods."""
    p = load_profile(profile_path)
    expected_pll = json.loads(generated(p)[PROJECT / p['pll']])
    clocks = [m['configuration'] for m in cp['primitive_metadata']
              if m['configuration']['kind'] == 'pll']
    if len(clocks) != 1:
        raise ValueError('expected exactly one physical PLL')
    actual = clocks[0]
    for name in ['fabric_output', 'feedback_output', 'parameters', 'attributes']:
        if actual[name] != expected_pll[name]:
            raise ValueError(f'physical PLL {name} does not match the platform profile')
    periods = [(1_000_000_000_000 + hz // 2) // hz
               for hz in [p['cpu_hz'], p['memory_hz']]]
    if integrated_jtck:
        periods.append(166666)
    if sorted(c['period_ps'] for c in cp['packing']['generated_clock_periods_ps']) != sorted(periods):
        raise ValueError('STA clock periods do not match the physical platform')
    for name in ['setup_uncertainty_ps', 'hold_uncertainty_ps']:
        if cp['timing'][name] != p['setup_hold_guard_ps']:
            raise ValueError('platform timing guard changed')
    return p


def generated(p):
    pll = json.loads((PROJECT / PLL_TEMPLATES[p['vco_hz']]).read_text())
    params = pll['parameters']
    if (params['FEEDBK_PATH'] != 'INT_OP'
            or p['reference_hz'] * int(params['CLKFB_DIV']) * int(params['CLKOP_DIV'])
            != p['vco_hz'] * int(params['CLKI_DIV'])):
        raise ValueError('PLL template does not generate the profile VCO')
    for prefix, hz in [('CLKOS', p['cpu_hz']), ('CLKOS2', p['memory_hz'])]:
        pll['parameters'][prefix + '_DIV'] = str(p['vco_hz'] // hz)
        pll['attributes']['FREQUENCY_PIN_' + prefix] = f'{hz / 1_000_000:g}'
    rtl = ('/// Generated by tools/user_platform.py from platform-user.json.\n'
           'package UserPlatform {\n'
           f"    const CPU_HZ: u64 = {p['cpu_hz']};\n"
           f"    const MEMORY_HZ: u64 = {p['memory_hz']};\n"
           f"    const PMP_DATA_STAGES: u32 = {p['pmp_data_stages']};\n"
           f"    const EARLY_ALU: bit = {int(p.get('early_alu', False))};\n"
           f"    const DIRECT_LOAD_RETURN: bit = {int(p.get('direct_load_return', False))};\n"
           '}\n')
    return {PROJECT / p['pll']: json.dumps(pll, indent=2) + '\n',
            PROJECT / 'src/UserPlatform.veryl': rtl}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for path, expected in generated(load_profile()).items():
        if args.write:
            path.write_text(expected)
        elif not path.exists() or path.read_text() != expected:
            raise SystemExit(f'{path} disagrees with platform-user.json; run --write')
    print('U-platform PLL and RTL constants agree with the profile')


if __name__ == '__main__':
    main()
