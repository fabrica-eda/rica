#!/usr/bin/env python3
"""Generate Zbb data, aliases and dependent-consumer checks from host integers."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MASK = (1 << 64) - 1
VALUES = [0, 1, 2, MASK, MASK - 1, 1 << 63, (1 << 63) - 1,
          0x80000000, 0xffffffff, 0xffffffff00000000, 0x1234567887654321]
BINARY = ['andn', 'orn', 'xnor', 'min', 'minu', 'max', 'maxu', 'rol', 'ror', 'rolw', 'rorw']
UNARY = ['clz', 'ctz', 'cpop', 'clzw', 'ctzw', 'cpopw', 'sext.b', 'sext.h', 'zext.h', 'orc.b', 'rev8']


def signed(x, width):
    x &= (1 << width) - 1
    return x - (1 << width) if x >> (width - 1) else x


def oracle(op, a, b=0):
    width = 32 if op.endswith('w') else 64
    low = a & ((1 << width) - 1)
    if op == 'andn': result = a & ~b
    elif op == 'orn': result = a | ~b
    elif op == 'xnor': result = ~(a ^ b)
    elif op in ['min', 'max']: result = (min if op == 'min' else max)(signed(a, 64), signed(b, 64))
    elif op in ['minu', 'maxu']: result = (min if op == 'minu' else max)(a, b)
    elif op.startswith(('rol', 'ror')):
        amount = b % width
        if op.startswith('rol'): amount = (-amount) % width
        result = ((low >> amount) | (low << ((-amount) % width))) & ((1 << width) - 1)
        if width == 32: result = signed(result, 32)
    elif op.startswith('clz'): result = width - low.bit_length()
    elif op.startswith('ctz'): result = (low & -low).bit_length() - 1 if low else width
    elif op.startswith('cpop'): result = low.bit_count()
    elif op == 'sext.b': result = signed(a, 8)
    elif op == 'sext.h': result = signed(a, 16)
    elif op == 'zext.h': result = a & 65535
    elif op == 'orc.b': result = sum((255 if (a >> (8*i)) & 255 else 0) << (8*i) for i in range(8))
    elif op == 'rev8': result = int.from_bytes(a.to_bytes(8, 'little'), 'big')
    else: raise ValueError(op)
    return result & MASK


def main():
    out = ROOT / 'tests/rv64-zbb'
    out.mkdir(exist_ok=True)
    for index, op in enumerate(BINARY + UNARY):
        if op in BINARY:
            cases = [(a, b) for a in VALUES for b in VALUES]
            if op.startswith(('rol', 'ror')):
                cases += [(a, b | 0xffff000000000000) for a in VALUES for b in range(64)]
        else:
            cases = [(a, 0) for a in VALUES + [1 << i for i in range(64)] + [MASK ^ (1 << i) for i in range(64)]]
        suffix = ', a1' if op in BINARY else ''
        lines = ['# Generated by riscv/tools/generate_rv64_zbb_tests.py.', '.include "test_macros.inc"',
                 '.section .text.init, "ax", @progbits', '.globl _start', '_start:',
                 '    la s0, cases', f'    li s1, {len(cases)}', 'loop:',
                 '    ld a0, 0(s0)', '    ld a1, 8(s0)', '    ld a2, 16(s0)',
                 f'    {op} a3, a0{suffix}', '    addi a4, a3, 1', '    addi a4, a4, -1',
                 '    bne a4, a2, fail', f'    {op} a0, a0{suffix}', '    bne a0, a2, fail']
        if op in BINARY:
            lines += ['    ld a0, 0(s0)', f'    {op} a1, a0, a1', '    bne a1, a2, fail']
        lines += ['    addi s0, s0, 24', '    addi s1, s1, -1', '    bnez s1, loop',
                  f'    {op} zero, a0{suffix}', '    bnez zero, fail', '    PASS', 'fail:',
                  f'    FAIL {60+index}', '.section .rodata, "a", @progbits', '.balign 8', 'cases:']
        lines += [f'    .dword 0x{a:016x}, 0x{b:016x}, 0x{oracle(op,a,b):016x}' for a,b in cases]
        (out/(op+'.S')).write_text('\n'.join(lines)+'\n')
    for op, base, width in [('rori','ror',64), ('roriw','rorw',32)]:
        lines = ['# Generated by riscv/tools/generate_rv64_zbb_tests.py.', '.include "test_macros.inc"',
                 '.section .text.init, "ax", @progbits', '.globl _start', '_start:']
        for amount in range(width):
            for a in VALUES:
                lines += [f'    li a0, 0x{a:016x}', f'    {op} a0, a0, {amount}', '    addi a1, a0, 0',
                          f'    li a2, 0x{oracle(base,a,amount):016x}', '    bne a1, a2, fail']
        lines += ['    PASS', 'fail:', '    FAIL 99']
        (out/(op+'.S')).write_text('\n'.join(lines)+'\n')
    (out/'link.ld').write_text((ROOT/'tests/rv64-m-benchmarks/link.ld').read_text())


if __name__ == '__main__':
    main()
