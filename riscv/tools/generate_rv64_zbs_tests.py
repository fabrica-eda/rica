#!/usr/bin/env python3
"""Generate all RV64 Zbs forms, bit positions, aliases and dependent consumers."""
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
MASK = (1 << 64) - 1
VALUES = [0, 1, 2, MASK, MASK - 1, 1 << 63, (1 << 63) - 1,
          0x80000000, 0xffffffff, 0xffffffff00000000, 0x1234567887654321]
BINARY = ['bclr', 'bext', 'binv', 'bset']


def oracle(op, a, b):
    bit = b % 64
    if op == 'bclr': return a & ~(1 << bit)
    if op == 'bext': return (a >> bit) & 1
    if op == 'binv': return a ^ (1 << bit)
    if op == 'bset': return a | (1 << bit)
    raise ValueError(op)


def main():
    out = ROOT / 'tests/rv64-zbs'
    out.mkdir(exist_ok=True)
    for index, op in enumerate(BINARY):
        cases = [(a, b | high) for a in VALUES for b in range(64) for high in [0, 0xffffffffffffffc0]]
        suffix = ', a1'
        lines = ['# Generated by riscv/tools/generate_rv64_zbs_tests.py.', '.include "test_macros.inc"',
                 '.section .text.init, "ax", @progbits', '.globl _start', '_start:',
                 '    la s0, cases', f'    li s1, {len(cases)}', 'loop:',
                 '    ld a0, 0(s0)', '    ld a1, 8(s0)', '    ld a2, 16(s0)',
                 f'    {op} a3, a0{suffix}', '    addi a4, a3, 1', '    addi a4, a4, -1',
                 '    bne a4, a2, fail', f'    {op} a0, a0{suffix}', '    bne a0, a2, fail']
        lines += ['    ld a0, 0(s0)', f'    {op} a1, a0, a1', '    bne a1, a2, fail']
        lines += ['    addi s0, s0, 24', '    addi s1, s1, -1', '    bnez s1, loop',
                  f'    {op} zero, a0{suffix}', '    bnez zero, fail', '    PASS', 'fail:',
                  f'    FAIL {60+index}', '.section .rodata, "a", @progbits', '.balign 8', 'cases:']
        lines += [f'    .dword 0x{a:016x}, 0x{b:016x}, 0x{oracle(op,a,b):016x}' for a,b in cases]
        (out/(op+'.S')).write_text('\n'.join(lines)+'\n')
    for base in BINARY:
        op, width = base + 'i', 64
        lines = ['# Generated by riscv/tools/generate_rv64_zbs_tests.py.', '.include "test_macros.inc"',
                 '.section .text.init, "ax", @progbits', '.globl _start', '_start:']
        for amount in range(width):
            for a in VALUES:
                lines += [f'    li a0, 0x{a:016x}', f'    {op} a0, a0, {amount}', '    addi a1, a0, 0',
                          f'    li a2, 0x{oracle(base,a,amount):016x}', '    bne a1, a2, fail']
        lines += ['    PASS', 'fail:', '    FAIL 99']
        (out/(op+'.S')).write_text('\n'.join(lines)+'\n')
    (out/'misa-b.S').write_text('''# Generated by riscv/tools/generate_rv64_zbs_tests.py.
.include "test_macros.inc"
.section .text.init, "ax", @progbits
.globl _start
_start:
    csrr a0, misa
    andi a1, a0, 2
    li a2, 2
    bne a1, a2, fail
    PASS
fail:
    FAIL 100
''')
    (out/'link.ld').write_text((ROOT/'tests/rv64-m-benchmarks/link.ld').read_text())


if __name__ == '__main__':
    main()
