#!/usr/bin/env python3
"""Build matched RV64I software and RV64M arithmetic workload sources."""
import hashlib
from pathlib import Path
import random
import struct

ROOT = Path(__file__).resolve().parents[1]
MASK = (1 << 64) - 1
SOFTWARE = {
    "multiply": """
    li t0, 0
1:  andi t1, a1, 1
    beqz t1, 2f
    add t0, t0, a0
2:  slli a0, a0, 1
    srli a1, a1, 1
    bnez a1, 1b
    mv a0, t0
    ret
""",
    "divide": """
    beqz a1, 4f
    li t0, 0
    li t1, 1
1:  bgeu a1, a0, 2f
    bltz a1, 2f
    slli a1, a1, 1
    slli t1, t1, 1
    j 1b
2:  bltu a0, a1, 3f
    sub a0, a0, a1
    or t0, t0, t1
3:  srli a1, a1, 1
    srli t1, t1, 1
    bnez t1, 2b
    mv a0, t0
    ret
4:  li a0, -1
    ret
""",
}


def main():
    output = ROOT / "tests/rv64-m-benchmarks"
    output.mkdir(exist_ok=True)
    (output / "link.ld").write_text((ROOT / "tests/rv64-memory/link.ld").read_text())
    rng = random.Random(0x64_20260907)
    pairs = [(rng.getrandbits(64), rng.getrandbits([8, 16, 32, 64][i % 4]) | 1)
             for i in range(256)]
    digest = hashlib.sha256(b"".join(struct.pack("<QQ", a, b) for a, b in pairs)).hexdigest()
    for operation in ["multiply", "divide"]:
        expected = sum(a * b if operation == "multiply" else a // b for a, b in pairs) & MASK
        for mode in ["soft", "m"]:
            code = SOFTWARE[operation] if mode == "soft" else (
                "    mul a0, a0, a1\n    ret\n" if operation == "multiply" else
                "    divu a0, a0, a1\n    ret\n")
            text = f'''# Generated by riscv/tools/generate_rv64_m_benchmarks.py.
# Shared input SHA256: {digest}
.include "test_macros.inc"
.section .text.init, "ax", @progbits
.globl _start
_start:
    la s0, pairs
    li s1, {len(pairs)}
    li s2, 0
loop:
    ld a0, 0(s0)
    ld a1, 8(s0)
    call operation
    add s2, s2, a0
    addi s0, s0, 16
    addi s1, s1, -1
    bnez s1, loop
    li s3, 0x{expected:016x}
    bne s2, s3, fail
    PASS
fail:
    FAIL 40
operation:
{code}
.section .rodata, "a", @progbits
.balign 8
pairs:
'''
            text += "".join(f"    .dword 0x{a:016x}, 0x{b:016x}\n" for a, b in pairs)
            (output / f"{mode}_{operation}.S").write_text(text)


if __name__ == "__main__":
    main()
