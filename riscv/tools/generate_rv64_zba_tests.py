#!/usr/bin/env python3
"""Generate RV64 Zba operand/alias regressions with host integer expected values."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MASK = (1 << 64) - 1
VALUES = [0, 1, 2, MASK, MASK - 1, 1 << 63, (1 << 63) - 1,
          0x80000000, 0xffffffff, 0xffffffff00000000, 0x1234567887654321]


def main():
    out = ROOT / "tests/rv64-zba"
    out.mkdir(exist_ok=True)
    for index, (name, shift, uw) in enumerate([
        ("add.uw", 0, True), ("sh1add", 1, False), ("sh2add", 2, False),
        ("sh3add", 3, False), ("sh1add.uw", 1, True), ("sh2add.uw", 2, True),
        ("sh3add.uw", 3, True),
    ]):
        lines = ["# Generated by riscv/tools/generate_rv64_zba_tests.py.",
                 '.include "test_macros.inc"', '.section .text.init, "ax", @progbits',
                 '.globl _start', '_start:', '    la s0, cases', f'    li s1, {len(VALUES)**2}',
                 'loop:', '    ld a0, 0(s0)', '    ld a1, 8(s0)', '    ld a2, 16(s0)',
                 f'    {name} a3, a0, a1', '    addi a4, a3, 1', '    addi a4, a4, -1',
                 '    bne a4, a2, fail', f'    {name} a3, a3, zero',
                 f'    {name} a0, a0, a1', '    bne a0, a2, fail',
                 '    ld a0, 0(s0)', f'    {name} a1, a0, a1', '    bne a1, a2, fail',
                 '    addi s0, s0, 24', '    addi s1, s1, -1', '    bnez s1, loop',
                 f'    {name} zero, a0, a1', '    bnez zero, fail', '    PASS',
                 'fail:', f'    FAIL {40+index}', '.section .rodata, "a", @progbits',
                 '.balign 8', 'cases:']
        for a in VALUES:
            for b in VALUES:
                expected = ((((a & 0xffffffff) if uw else a) << shift) + b) & MASK
                lines.append(f'    .dword 0x{a:016x}, 0x{b:016x}, 0x{expected:016x}')
        (out / (name + '.S')).write_text('\n'.join(lines) + '\n')
    lines = ['# Generated by riscv/tools/generate_rv64_zba_tests.py.',
             '.include "test_macros.inc"', '.section .text.init, "ax", @progbits',
             '.globl _start', '_start:']
    for shift in range(64):
        for a in [0xffffffffffffffff, 0x1234567880000001]:
            expected = ((a & 0xffffffff) << shift) & MASK
            lines += [f'    li a0, 0x{a:016x}', f'    slli.uw a0, a0, {shift}',
                      '    addi a1, a0, 1', '    addi a1, a1, -1',
                      f'    li a2, 0x{expected:016x}', '    bne a1, a2, fail']
    lines += ['    PASS', 'fail:', '    FAIL 47']
    (out / 'slli.uw.S').write_text('\n'.join(lines) + '\n')
    (out / 'link.ld').write_text((ROOT / 'tests/rv64-m-benchmarks/link.ld').read_text())


if __name__ == "__main__":
    main()
