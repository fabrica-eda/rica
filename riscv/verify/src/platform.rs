//! Board clock and PMP configuration shared by native and timed simulation.
use std::{error::Error, fs, path::Path};

#[derive(Clone, Copy, Debug)]
pub struct PlatformTiming {
    pub cpu_hz: u64,
    pub memory_hz: u64,
    pub pmp_data_stages: u64,
    pub early_alu: bool,
    pub direct_load_return: bool,
}

impl PlatformTiming {
    pub fn memory_divisor(self) -> usize {
        (self.cpu_hz / self.memory_hz) as usize
    }

    pub fn elapsed_ps(self, cycles: usize) -> u128 {
        cycles as u128 * 1_000_000_000_000 / u128::from(self.cpu_hz)
    }
}

pub fn hardware_platform(project: &Path, user: bool) -> Result<PlatformTiming, Box<dyn Error>> {
    if !user {
        return Ok(PlatformTiming {
            cpu_hz: 124_800_000,
            memory_hz: 62_400_000,
            pmp_data_stages: 3,
            early_alu: false,
            direct_load_return: false,
        });
    }
    let record: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(project.join("platform-user.json"))?)?;
    let integer = |name| record[name].as_u64().ok_or("invalid platform integer");
    let result = PlatformTiming {
        cpu_hz: integer("cpu_hz")?,
        memory_hz: integer("memory_hz")?,
        pmp_data_stages: integer("pmp_data_stages")?,
        early_alu: record["early_alu"]
            .as_bool()
            .ok_or("invalid early_alu flag")?,
        direct_load_return: record["direct_load_return"]
            .as_bool()
            .ok_or("invalid direct_load_return flag")?,
    };
    if result.memory_hz == 0
        || result.cpu_hz == 0
        || result.cpu_hz % result.memory_hz != 0
        || !matches!(result.memory_divisor(), 1 | 2)
        || !matches!(result.pmp_data_stages, 2 | 3)
        || (result.direct_load_return && result.cpu_hz != result.memory_hz)
        || integer("setup_hold_guard_ps")? != 194
    {
        return Err("invalid U-platform clock/stage configuration".into());
    }
    let expected = format!(
        "/// Generated by tools/user_platform.py from platform-user.json.\npackage UserPlatform {{\n    const CPU_HZ: u64 = {};\n    const MEMORY_HZ: u64 = {};\n    const PMP_DATA_STAGES: u32 = {};\n    const EARLY_ALU: bit = {};\n    const DIRECT_LOAD_RETURN: bit = {};\n}}\n",
        result.cpu_hz,
        result.memory_hz,
        result.pmp_data_stages,
        u8::from(result.early_alu),
        u8::from(result.direct_load_return)
    );
    if fs::read_to_string(project.join("src/UserPlatform.veryl"))? != expected {
        return Err(
            "U-platform RTL constants are stale; run tools/user_platform.py --write".into(),
        );
    }
    Ok(result)
}
